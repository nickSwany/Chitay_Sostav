    private val index: Map<String, Additive> = all.associateBy { it.eNumber }

    fun findByENumber(eNumber: String): Additive? = index[eNumber.lowercase().trim()]

    fun findByText(text: String): List<Additive> {
        val lower = text.lowercase()
        return all.filter { additive ->
            additive.aliases.any { alias ->
                val escaped = Regex.escape(alias)
                Regex("(?<![а-яёa-z\\d])$escaped(?![а-яёa-z\\d])", RegexOption.IGNORE_CASE)
                    .containsMatchIn(lower)
            }
        }
    }
